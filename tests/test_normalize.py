import pytest

from core.normalize import normalize


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("Труба  БЕСШОВНАЯ", "труба бесшовная"),
        ("89*8", "89х8"),
        ("114x8", "114х8"),
        ("60 х 5.0", "60х5.0"),
        ("114×7,4", "114х7.4"),
        ("ТУ 14-3Р-167-2019, ГОСТ 632-80", "ту 14-3р-167-2019, гост 632-80"),
        ("K52", "к52"),
        ("09G2S", "09g2s"),
        ("тр. б/ш 89х8", "труба бесшовная 89х8"),
        ("тр бесш. гр.4", "труба бесшовная группа 4"),
        ("гр 2", "группа 2"),
        ("Труба э/с", "труба электросварная"),
        ("Труба эл/св", "труба электросварная"),
        ("труба эл.св.", "труба электросварная"),
        ("ст.09Г2С", "сталь 09г2с"),
        ("гр.пр. Е", "группа прочности е"),
        ("исп. А", "исполнение а"),
        ("ГОСТ 632", "гост 632"),
        ("град.С", "град.с"),
        ("Ёлка", "елка"),
    ],
)
def test_normalize(text, expected):
    assert normalize(text) == expected
